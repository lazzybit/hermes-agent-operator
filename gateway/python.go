var installRequirements = installRequirementsDefault

type pythonDecl struct {
	deps []string
	skip bool
}

// writeSiteCustomizer leaves a sitecustomize module in the dependency
// directory. Python imports it from PYTHONPATH during startup and moves
// those dependency directories to the end of sys.path, after the sealed
// Hermes environment, so a plugin package cannot replace a core module.
func writeSiteCustomizer(depsDir string) error {
	if err := os.MkdirAll(depsDir, 0o755); err != nil {
		return err
	}
	const source = `# Generated by hermes-gateway-init. Moves plugin dependency paths
# behind the sealed Hermes environment.
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
prefix = os.path.dirname(here) + os.sep
moved = [path for path in sys.path if path == here or path.startswith(prefix)]
if moved:
    sys.path[:] = [path for path in sys.path if path != here and not path.startswith(prefix)]
    for path in moved:
        if path not in sys.path:
            sys.path.append(path)
`
	return os.WriteFile(filepath.Join(depsDir, "sitecustomize.py"), []byte(source), 0o644)
}

// preparePython installs dependencies declared by a plugin pyproject.toml.
// Official Hermes images seal the runtime environment and disable lazy
// installs, so projecting the files is not enough. This does not run
// `hermes plugins` or the catalog CLI. A plugin that sets
// python_runtime: external keeps its own interpreter and is skipped.
func preparePython(pluginDir, siteDir string) error {
	decl, err := readPythonDecl(pluginDir)
	if err != nil {
		return err
	}
	if decl.skip || len(decl.deps) == 0 {
		return nil
	}
	return installRequirements(siteDir, decl.deps)
}

func readPythonDecl(pluginDir string) (pythonDecl, error) {
	if externalRuntime(pluginDir) {
		return pythonDecl{skip: true}, nil
	}
	project := filepath.Join(pluginDir, "pyproject.toml")
	data, err := os.ReadFile(project)
	if os.IsNotExist(err) {
		return pythonDecl{}, nil
	}
	if err != nil {
		return pythonDecl{}, err
	}
	deps, err := projectDependencies(data)
	if err != nil {
		return pythonDecl{}, fmt.Errorf("pyproject.toml: %w", err)
	}
	return pythonDecl{deps: deps}, nil
}

func externalRuntime(pluginDir string) bool {
	for _, name := range []string{"plugin.yaml", "plugin.yml"} {
		data, err := os.ReadFile(filepath.Join(pluginDir, name))
		if err != nil {
			continue
		}
		scanner := bufio.NewScanner(bytes.NewReader(data))
		for scanner.Scan() {
			line := stripComment(scanner.Text())
			line = strings.TrimSpace(line)
			key, value, ok := strings.Cut(line, ":")
			if !ok || strings.TrimSpace(key) != "python_runtime" {
				continue
			}
			value = strings.Trim(strings.TrimSpace(value), `"'`)
			if value == "external" {
				return true
			}
		}
	}
	return false
}

func projectDependencies(data []byte) ([]string, error) {
	inProject := false
	inDeps := false
	var deps []string
	sawDeps := false
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		raw := scanner.Text()
		if inDeps {
			done, items, err := parseDepLine(raw)
			if err != nil {
				return nil, err
			}
			deps = append(deps, items...)
			if done {
				inDeps = false
			}
			continue
		}
		line := strings.TrimSpace(stripComment(raw))
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "[") && strings.HasSuffix(line, "]") {
			inProject = line == "[project]"
			continue
		}
		if !inProject {
			continue
		}
		key, value, ok := strings.Cut(line, "=")
		if !ok || strings.TrimSpace(key) != "dependencies" {
			continue
		}
		if sawDeps {
			return nil, fmt.Errorf("duplicate dependencies")
		}
		sawDeps = true
		value = strings.TrimSpace(value)
		if !strings.HasPrefix(value, "[") {
			return nil, fmt.Errorf("dependencies must be an array")
		}
		done, items, err := parseDepLine(value)
		if err != nil {
			return nil, err
		}
		deps = append(deps, items...)
		inDeps = !done
	}
	if err := scanner.Err(); err != nil {
		return nil, err
	}
	if inDeps {
		return nil, fmt.Errorf("dependencies array is not closed")
	}
	return deps, nil
}

func parseDepLine(line string) (done bool, deps []string, err error) {
	s := stripComment(line)
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case ' ', '\t', '\r', ',', '[', '\n':
			continue
		case ']':
			return true, deps, nil
		case '"', '\'':
			item, next, err := readQuoted(s, i)
			if err != nil {
				return false, nil, err
			}
			if strings.TrimSpace(item) == "" {
				return false, nil, fmt.Errorf("empty dependency")
			}
			deps = append(deps, item)
			i = next - 1
		default:
			return false, nil, fmt.Errorf("invalid dependencies array")
		}
	}
	return false, deps, nil
}

func readQuoted(s string, start int) (string, int, error) {
	quote := s[start]
	var b strings.Builder
	for i := start + 1; i < len(s); i++ {
		if s[i] == '\\' && i+1 < len(s) {
			b.WriteByte(s[i+1])
			i++
			continue
		}
		if s[i] == quote {
			return b.String(), i + 1, nil
		}
		b.WriteByte(s[i])
	}
	return "", 0, fmt.Errorf("unterminated dependency string")
}

func stripComment(line string) string {
	var b strings.Builder
	inQuote := byte(0)
	for i := 0; i < len(line); i++ {
		c := line[i]
		if inQuote != 0 {
			b.WriteByte(c)
			if c == '\\' && i+1 < len(line) {
				b.WriteByte(line[i+1])
				i++
				continue
			}
			if c == inQuote {
				inQuote = 0
			}
			continue
		}
		if c == '"' || c == '\'' {
			inQuote = c
			b.WriteByte(c)
			continue
		}
		if c == '#' {
			break
		}
		b.WriteByte(c)
	}
	return b.String()
}

func installRequirementsDefault(site string, deps []string) error {
	if custom := os.Getenv("HERMES_PLUGIN_INSTALLER"); custom != "" {
		return runCommand(custom, append([]string{site}, deps...))
	}
	uv, err := findUV()
	if err != nil {
		return fmt.Errorf("plugin pyproject.toml requires uv from the Hermes image; the sealed venv has no pip: %w", err)
	}
	return runCommand(uv, append([]string{"pip", "install", "--python", hermesPython(), "--target", site, "--link-mode", "copy"}, deps...))
}

func hermesPython() string {
	if python := os.Getenv("HERMES_PYTHON"); python != "" {
		return python
	}
	return "/opt/hermes/.venv/bin/python"
}

// findUV locates the installer shipped in the official Hermes image.
// uv is internal PM tooling, so installed_package("uv") refuses it.
// The sealed /opt/hermes/.venv has no pip module.
func findUV() (string, error) {
	if path, err := exec.LookPath("uv"); err == nil {
		return path, nil
	}
	var tried []string
	for _, facts := range factsCandidates() {
		tried = append(tried, facts)
		if path, err := uvBinaryFromFacts(facts); err == nil {
			return path, nil
		}
	}
	for _, python := range []string{"/usr/bin/python3", "/usr/local/bin/python3"} {
		tried = append(tried, python)
		if path, err := uvFromPython(python); err == nil {
			return path, nil
		}
	}
	return "", fmt.Errorf("uv was not on PATH or in the Hermes tool store (%s)", strings.Join(tried, ", "))
}

func factsCandidates() []string {
	var out []string
	if dir := os.Getenv("HERMES_RUNTIME_DIR"); dir != "" {
		out = append(out, filepath.Join(dir, "facts.json"))
	}
	out = append(out, "/opt/hermes/tools/facts.json")
	return out
}

func uvBinaryFromFacts(factsPath string) (string, error) {
	data, err := os.ReadFile(factsPath)
	if err != nil {
		return "", err
	}
	var facts struct {
		Packages map[string]struct {
			Entry string `json:"entry"`
		} `json:"packages"`
	}
	if err := json.Unmarshal(data, &facts); err != nil {
		return "", err
	}
	entry := facts.Packages["uv"].Entry
	if entry == "" || entry == "." || entry == ".." || strings.ContainsAny(entry, `/\`) {
		return "", fmt.Errorf("%s has no uv entry", factsPath)
	}
	root := filepath.Dir(factsPath)
	for _, rel := range []string{"uv", filepath.Join("bin", "uv")} {
		path := filepath.Join(root, entry, rel)
		info, err := os.Stat(path)
		if err != nil || info.IsDir() || info.Mode()&0o111 == 0 {
			continue
		}
		return path, nil
	}
	return "", fmt.Errorf("%s uv entry %s has no executable", factsPath, entry)
}

const uvLauncherSnippet = `from pm import uv_launcher
path = uv_launcher("uv")
if not path:
    raise SystemExit("uv launcher is not installed")
print(path)
`

func uvFromPython(python string) (string, error) {
	if _, err := os.Stat(python); err != nil {
		return "", err
	}
	cmd := exec.Command(python, "-c", uvLauncherSnippet)
	cmd.Env = append(os.Environ(), "PYTHONPATH=/opt/hermes"+string(os.PathListSeparator)+os.Getenv("PYTHONPATH"))
	if info, err := os.Stat("/opt/hermes"); err == nil && info.IsDir() {
		cmd.Dir = "/opt/hermes"
	}
	out, err := cmd.Output()
	if err != nil {
		return "", err
	}
	path := strings.TrimSpace(string(out))
	info, err := os.Stat(path)
	if err != nil || info.IsDir() || info.Mode()&0o111 == 0 {
		return "", fmt.Errorf("%s did not report an executable uv", python)
	}
	return path, nil
}

func runCommand(name string, args []string) error {
	cmd := exec.Command(name, args...)
	cmd.Stdout = os.Stderr
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	return nil
}
